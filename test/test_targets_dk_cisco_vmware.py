FL = '/suite-api/api/fleet-management/certificate-management'


def ops_routes(csr=None, version=(9, 1), models=None, state='COMPLETED'):
    if models is None:
        models = [{'certificateResourceKey': 'c-77', 'applianceFqdn': 'vc01.example.test',
                   'appliance': 'VCENTER', 'category': 'TLS_CERT'},
                  {'certificateResourceKey': 'c-78', 'applianceFqdn': 'nsx.example.test'}]
    return [
        ('POST', r'/auth/token/acquire$', (200, {'token': 'OPS', 'validity': 1})),
        ('POST', r'/auth/token/release$', (200, {})),
        ('GET', r'/versions/current$', (200, {'releaseName': 'VCF Operations',
                                              'major': version[0], 'minor': version[1]})),
        ('POST', r'/certificates/query\?', (200, {'vcfCertificateModels': models})),
        ('POST', r'/certificate-management/csrs$', (200, {'requestId': 'w-1',
                                                          'state': 'INPROGRESS'})),
        ('GET', r'/workflows/requests/w-[12]$', (200, {'state': state})),
        ('GET', r'/certificate-management/csrs\?certificateId=c-77$', (200, {
            'certificateSignatureInfo': [{'csr': csr or a_csr(['vc01.example.test'])}]})),
        ('PUT', r'/certificates/c-77$', (202, {'requestId': 'w-2'})),
    ]


class Ops(unittest.TestCase):
    def test_csr(self):
        want = a_csr(['vc01.example.test', '10.0.0.10'], 'rsa-4096')
