class FakeCucm(object):
    """CUCM's CLI: the lines typed in one session, answered one by one."""
    def __init__(self, csr=None, trust=(), version='15.0.1.13900-234', own_serial=None):
        self.csr = csr
        self.trust = list(trust)            # file names in tomcat-trust
        self.version = version
        self.own_serial = own_serial
        self.sessions = []
        self.ssh = FakeSsh([(r'', self.answer)])

    def answer(self, cmd, inp):
        assert cmd == '', cmd
        lines = inp.split('\n')
        self.sessions.append(lines)
        out = []
        i = 0
        while i < len(lines):
            ln = lines[i]
            i += 1
            if ln == 'show version active':
                out.append('Active Master Version: %s\nActive Version Installed Software '
                           'Options:\n' % self.version)
            elif ln.startswith('set csr gen '):
                out.append('Successfully Generated CSR for %s\n' % ln.split()[-1])
            elif ln.startswith('show csr own '):
                out.append(self.csr or '')
            elif ln == 'show cert list trust':
                out.append(''.join('tomcat-trust/%s: Trust Certificate\n' % n
                                   for n in self.trust))
            elif ln == 'show cert list own':
                out.append('tomcat/tomcat.pem: Self-signed certificate generated by system\n')
            elif ln.startswith('set cert import '):
                out.append('Paste the Certificate and Hit Enter\n')
                pem = []
                while i < len(lines) and lines[i] != '':
                    pem.append(lines[i])
                    i += 1
                i += 1
                if ln.startswith('set cert import trust'):
                    cn = pki.cert_info('\n'.join(pem))['subject'].get('CN', 'x')
                    self.trust.append(U.file_stem(cn) + '.pem')
                    out.append('Import of trust certificate is successful\n')
                else:
                    self.own_serial = pki.cert_info('\n'.join(pem))['serial']
                    out.append('Successfully imported certificate for tomcat.\nPlease restart '
                               'services related to tomcat for the new certificate to become '
                               'active.\n')
            elif ln.startswith('show cert own '):
                out.append('[\n  Version: V3\n  SerialNumber: [ %s ]\n]\n' % (
                    self.own_serial or '00'))
            elif ln.startswith('utils service restart '):
                out.append('Service Manager is running\n%s[STARTED]\n' % ln[22:])
            elif ln in ('exit', ''):
                pass
            else:
                out.append('Executed command unsuccessfully\nInvalid command: %s\n' % ln)
        return 0, ''.join(out), ''

    def typed(self):
        return [ln for s in self.sessions for ln in s if ln and not ln.startswith(
            ('-----', 'MI')) and not re.match(r'^[A-Za-z0-9+/=]{20,}$', ln)]


