#!/usr/bin/env python3
"""Make deploy/agent/acme_agent_winroles.py - the PowerShell of the Windows roles as acme-agent
runs them - from acmelib/plugins/targets/_win_roles.py, the very templates the OpenSSH target
(windows_ssh) renders: one logic, two renderings (docs/target-agent.md "Windows: the roles").

    python3 tools/gen_agent_winroles.py           write it
    python3 tools/gen_agent_winroles.py --check   exit 1 when the file there is not what
                                                  this makes (test_agent_windows_parity.py)

The agent's file holds data only (text of fixed scripts, the checks of their values): the agent
runs each script with the values of a job in a JSON file of its own stage folder ($o), never
with anything of a job in the script's text.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'deploy', 'agent', 'acme_agent_winroles.py')

HEAD = '''"""acme_agent_winroles.py - the Windows roles of acme-agent (1.0.120, docs/target-agent.md
"Windows: the roles"): GENERATED by tools/gen_agent_winroles.py from
acmelib/plugins/targets/_win_roles.py - do not edit (test_agent_windows_parity.py fails when
the two differ).

The same templates the target "Windows server (OpenSSH + PowerShell)" renders with the values in
the text; here rendered once with every value read from $o - the job's values, which the agent
writes as JSON into root's stage folder (ACME_WIN_IN) after checking them with SCHEMA, a
password only in an environment variable (ACME_PFX_PASSWORD, ACME_CCS_PASSWORD). Data only:
nothing here runs by itself; acme_agent_wincert.py runs these scripts when the policy allows
the role (allow role NAME, allow key-read ACCOUNT).
"""

'''


def make():
    sys.path.insert(0, ROOT)
    from acmelib.plugins.targets import _win_roles as WR
    scripts = WR.agent_scripts()
    out = [HEAD]
    out.append('# the roles in the order they run: (key, title in the steps, what it needs: '
               '"pfx" a PKCS#12 file,\n# "ccs" the PKCS#12 of the Central Certificate Store, '
               'None)\n')
    out.append('ROLES = [\n')
    for key, _label, title, need in WR.ROLES:
        out.append('    (%r, %r, %r),\n' % (key, title, need))
    out.append(']\n\n')
    out.append('# the values of each role: {name: (type, the regular expression a value or '
               'each item matches)};\n# "agent": a path the agent puts in (its own stage '
               'folder), never acme\'s\n')
    out.append('SCHEMA = {\n')
    for key in sorted(WR.SCHEMA):
        out.append('    %r: {\n' % key)
        for name in sorted(WR.SCHEMA[key]):
            out.append('        %r: %r,\n' % (name, WR.SCHEMA[key][name]))
        out.append('    },\n')
    out.append('}\n\n')
    out.append('# the whole PowerShell of each (head, helpers, body): $j is the job\'s JSON, '
               '$o = $j.o its values\n')
    out.append('SCRIPTS = {\n')
    for key in sorted(scripts):
        out.append('    %r: (\n' % key)
        lines = scripts[key].split('\n')
        for i, line in enumerate(lines):
            out.append('        %r\n' % (line + ('\n' if i < len(lines) - 1 else '')))
        out.append('    ),\n')
    out.append('}\n')
    return ''.join(out)


def main(argv):
    text = make()
    if '--check' in argv:
        try:
            with open(OUT, encoding='utf-8') as f:
                have = f.read()
        except OSError:
            have = None
        if have != text:
            print('%s is not what tools/gen_agent_winroles.py makes - run it' % OUT)
            return 1
        print('in sync')
        return 0
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote %s' % OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
